# Keep reset/default OUTSIDE the Enum so they are not counted as colors.
Colors.RESET = "\033[0m"
Colors.DEFAULT = "\033[39m"
Colors.BOLD = "\033[1m"
Colors.UNDERLINE = "\033[4m"

# This is what makes this work:
#     from colors import colors as c
colors = Colors


def print_palette() -> None:
    global colors
    """Print all named colors in four columns."""
    print(f"{len(colors)} named colors\n")

    for index, color in enumerate(colors, start=1):
        print(
            f"{color.value}{color.name:<24}{colors.RESET}",
            end="\n" if index % 4 == 0 else "  ",
        )

    if len(colors) % 4:
        print()

    print(colors.RESET, end="")


if __name__ == "__main__":
    print_palette()
